export const useT = (lang) => {
  return (path) => {
    const keys = path.split('.');
    let val = translations[lang] || translations.en;
    for (const k of keys) {
      val = val?.[k];
      if (val === undefined) {
        // fallback to en
        let fb = translations.en;
        for (const k2 of keys) {
          fb = fb?.[k2];
        }
        return fb ?? path;
      }
    }
    return val;
  };
};